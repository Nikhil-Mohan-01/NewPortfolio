export type AppId = (typeof apps)[number]["id"];
export type App = (typeof apps)[number];

export function pixelIcon(app: App) {
  const pixels: string[] = [];
  app.icon.forEach((row, y) => {
    [...row].forEach((pixel, x) => {
      if (pixel === "#") pixels.push(`${x}em ${y}em currentColor`);
    });
  });
  return `<span class="pixel-icon" aria-hidden="true" style="--app-color:${app.color}"><i style="box-shadow:${pixels.join(",")}"></i></span>`;
}
